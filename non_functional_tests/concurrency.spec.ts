// Helper function to generate focalboard-compatible random IDs
function generateGuid() {
  const chars = 'abcdefghijklmnopqrstuvwxyz0123456789';
  let result = '';
  for (let i = 0; i < 26; i++) {
    result += chars.charAt(Math.floor(Math.random() * chars.length));
  }
  return result;
}

// Helper function to register a user via the API
async function registerUser(request: any, username: string, email: string, password: string, signupToken: string = '') {
  const response = await request.post('/api/v2/register', {
    data: {
      username,
      email,
      password,
      token: signupToken,
    },
    headers: {
      'X-Requested-With': 'XMLHttpRequest',
    }
  });
  return response;
}

// Helper to log in a user and return the token and user ID
async function loginUser(request: any, username: string, password: string) {
  const response = await request.post('/api/v2/login', {
    data: {
      type: 'normal',
      username,
      password,
    },
    headers: {
      'X-Requested-With': 'XMLHttpRequest',
    }
  });
  expect(response.status()).toBe(200);
  const data = await response.json();
  
  // Get Me to retrieve user ID
  const meResponse = await request.get('/api/v2/users/me', {
    headers: {
      'Authorization': `Bearer ${data.token}`,
      'X-Requested-With': 'XMLHttpRequest',
    }
  });
  expect(meResponse.status()).toBe(200);
  const meData = await meResponse.json();
  
  return { token: data.token, userId: meData.id };
}

// Helper to inject local storage for login bypass in Playwright context
async function loginBypass(page: any, token: string) {
  // First go to /login to establish the origin context
  await page.goto('/login');
  // Inject tokens into localStorage
  await page.evaluate((sessionToken: string) => {
    window.localStorage.setItem('focalboardSessionId', sessionToken);
    window.localStorage.setItem('welcomePageViewed', 'true');
    window.localStorage.setItem('language', 'en');
  }, token);
}


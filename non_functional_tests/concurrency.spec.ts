  test('CON-02: Conflicto de Schema y Datos - Card Move vs Column Delete', async ({ request }) => {
    console.log('\n--- Running CON-02: Card Move vs Column Delete ---');
    
    // Fetch the created board metadata using API
    const boardResponse = await request.get(`/api/v2/boards/${boardId}`, {
      headers: {
        'Authorization': `Bearer ${user1Token}`,
        'X-Requested-With': 'XMLHttpRequest',
      }
    });
    expect(boardResponse.status()).toBe(200);
    const boardData = await boardResponse.json();
    
    // Check if cardProperties exist and contain status select options
    const cardProperties = boardData.cardProperties || [];
    const statusProp = cardProperties.find((p: any) => p.name === 'Status' && p.type === 'select');
    if (!statusProp) {
      console.log('No Status property found, skipping CON-02.');
      return;
    }
    
    const options = statusProp.options || [];
    if (options.length < 2) {
      console.log('Not enough options/columns on board to perform test.');
      return;
    }
    
    const optionToMoveTo = options[options.length - 1]; // Let's use the last column ("Done")
    const optionToMoveToId = optionToMoveTo.id;
    console.log(`Target column to move to and delete: "${optionToMoveTo.value}" (ID: ${optionToMoveToId})`);

    // Prepare User 1 move request payload (Patch Card block)
    const cardPatchPayload = {
      updatedFields: {
        properties: {
          [statusProp.id]: optionToMoveToId
        }
      }
    };

    // Prepare User 2 schema update payload (Patch Board block options)
    // We remove the target option from the options list
    const updatedOptions = options.filter((opt: any) => opt.id !== optionToMoveToId);
    const updatedCardProperties = cardProperties.map((p: any) => {
      if (p.id === statusProp.id) {
        return { ...p, options: updatedOptions };
      }
      return p;
    });

    const boardPatchPayload = {
      updatedCardProperties: updatedCardProperties
    };

    console.log('Sending concurrent Card Move (U1) and Column Delete (U2) requests...');
    const responses = await Promise.all([
      // U1 moves card
      request.patch(`/api/v2/boards/${boardId}/blocks/${cardId}`, {
        headers: {
          'Authorization': `Bearer ${user1Token}`,
          'X-Requested-With': 'XMLHttpRequest',
          'Content-Type': 'application/json'
        },
        data: cardPatchPayload
      }),
      // U2 deletes option/column from board
      request.patch(`/api/v2/boards/${boardId}`, {
        headers: {
          'Authorization': `Bearer ${user2Token}`,
          'X-Requested-With': 'XMLHttpRequest',
          'Content-Type': 'application/json'
        },
        data: boardPatchPayload
      })
    ]);

    console.log(`Card Move Response Status: ${responses[0].status()}`);
    console.log(`Column Delete Response Status: ${responses[1].status()}`);

    // Verify both operations are processed gracefully by the server
    expect(responses[0].status()).toBe(200);
    expect(responses[1].status()).toBe(200);

    // Give time for processing
    await new Promise(resolve => setTimeout(resolve, 1000));

    // Verify that the card state is consistent: the card properties still exist
    const finalCardResponse = await request.get(`/api/v2/boards/${boardId}/blocks?block_id=${cardId}`, {
      headers: {
        'Authorization': `Bearer ${user1Token}`,
        'X-Requested-With': 'XMLHttpRequest',
      }
    });
    expect(finalCardResponse.status()).toBe(200);
    const finalCardData = await finalCardResponse.json();
    const finalProperties = finalCardData[0]?.fields?.properties || {};
    console.log('Final Card Properties:', JSON.stringify(finalProperties));

    // Verify the board schema: the target column was successfully deleted
    const finalBoardResponse = await request.get(`/api/v2/boards/${boardId}`, {
      headers: {
        'Authorization': `Bearer ${user1Token}`,
        'X-Requested-With': 'XMLHttpRequest',
      }
    });
    expect(finalBoardResponse.status()).toBe(200);
    const finalBoardData = await finalBoardResponse.json();
    const finalProps = finalBoardData.cardProperties || [];
    const finalStatusProp = finalProps.find((p: any) => p.id === statusProp.id);
    const finalOptions = finalStatusProp?.options || [];
    
    console.log('Final Board Schema Options:', JSON.stringify(finalOptions));
    expect(finalOptions.some((opt: any) => opt.id === optionToMoveToId)).toBe(false);
  });

  test('CON-03: Consistencia de WebSockets - Disconnection and Catch-up', async ({ baseURL }) => {
    console.log('\n--- Running CON-03: Consistencia de WebSockets ---');
    const browser = await chromium.launch();

    // Context for User 1 (will be disconnected and reconnected)
    const context1 = await browser.newContext({ baseURL });
    const page1 = await context1.newPage();
    await loginBypass(page1, user1Token);

    // Context for User 2 (will perform changes while User 1 is offline)
    const context2 = await browser.newContext({ baseURL });
    const page2 = await context2.newPage();
    await loginBypass(page2, user2Token);

    // Go to board page
    await page1.goto(`/${boardId}`);
    await page2.goto(`/${boardId}`);

    // Wait for page load
    await expect(page1.locator('.BoardComponent')).toBeVisible();
    await expect(page2.locator('.BoardComponent')).toBeVisible();

    console.log('Disconnecting User 1 from network...');
    await context1.setOffline(true);

    const offlineText = `Card created by U2 while U1 offline ${Date.now()}`;
    console.log(`User 2 is creating a new card: "${offlineText}"`);

    // User 2 adds a card using UI
    await page2.locator('.ViewHeader .ButtonWithMenu .button-text').click();
    await expect(page2.locator('.CardDetail').first()).toBeVisible();
    await page2.locator('.CardDetail .EditableArea.title').first().click();
    await page2.locator('.CardDetail .EditableArea.title').first().fill(offlineText);
    await page2.locator('.CardDetail .EditableArea.title').first().blur();
    
    // Close card modal for User 2
    await page2.locator('.Dialog Button[title=\'Close dialog\']').click();
    await expect(page2.locator('.CardDetail').first()).not.toBeVisible();
    
    // Ensure card is visible on User 2's board
    await expect(page2.locator('.KanbanCard', { hasText: offlineText })).toBeVisible();

    // Verify card is NOT yet visible on User 1's board (since they are offline)
    console.log('Verifying that User 1 (offline) has not received the new card...');
    const cardOnU1 = page1.locator('.KanbanCard', { hasText: offlineText });
    await expect(cardOnU1).not.toBeVisible({ timeout: 2000 });

    console.log('Reconnecting User 1 network...');
    await context1.setOffline(false);

    // Wait for Websocket catch-up / reconciliation to push the updates
    console.log('Waiting for WebSocket catch-up/reconciliation...');
    
    // Verify that the new card is eventually automatically synced to User 1's UI
    await expect(cardOnU1).toBeVisible({ timeout: 15000 });
    console.log('User 1 UI automatically caught up with User 2 modifications! WebSocket reconciliation success.');

    await context1.close();
    await context2.close();
    await browser.close();
  });

